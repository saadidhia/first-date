export function getGuide(slug: string) {
  return GUIDES.find((g) => g.slug === slug)
}

/** Formats a YYYY-MM-DD date in Arabic, e.g. "8 نوفمبر 2026" */
export function guideDate(date: string) {
  const months = [
    'جانفي',
    'فيفري',
    'مارس',
    'أفريل',
    'ماي',
    'جوان',
    'جويلية',
    'أوت',
    'سبتمبر',
    'أكتوبر',
    'نوفمبر',
    'ديسمبر',
  ]
  const [y, m, d] = date.split('-').map(Number)
  return `${d} ${months[m - 1]} ${y}`
}

/** Rough reading time in minutes (Arabic reads at about 180 words a minute) */
export function readingMinutes(g: Guide) {
  const text = [
    g.intro,
    g.takeaway,
    ...g.sections.flatMap((s) => [s.h, ...(s.p ?? []), ...(s.list ?? [])]),
  ].join(' ')
  return Math.max(2, Math.round(text.split(/\s+/).length / 180))
}
