// ملك القعدة, the board game with friends. The player who rolled doesn't answer: the others decide their fate.
//
// "صحابك يحكمو" questions are about the player who rolled. {name} is their name and
// {masc|fem} picks the word for their gender. Each option carries how far it moves them, and
// the points of every friend's vote add up. The points are a surprise (only the player who
// rolled sees them), so they don't simply follow kind/roast: on some questions the roast is
// worth +1 or +2 and the dull answer costs a point.
// Three levels like the couple bank: light at the start, bolder roasts near the wedding.
//
// Dares (🎤 تحدّي) are done out loud on the voice call; the friends then vote with DARE_VOTES.
// Append only: ids are fq_<e|m|h>_<position> and fd_<position>.
export type FriendsOption = [text: string, move: number]
export type FriendsRawQuestion = [
  text: string,
  a: FriendsOption,
  b: FriendsOption,
  c: FriendsOption,
]

