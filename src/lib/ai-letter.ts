function overall(balance: number) {
  if (balance >= 80)
    return 'شخصيتك متوازنة برشا: في أغلب المواقف تختار الوسط، لا تهرب ولا تهجم. أما خلّيني نقلّك وين نشوفك تنجم تكبر أكثر.'
  if (balance >= 60)
    return 'عندك قاعدة صحيحة: في برشا مواقف تعرف تتصرّف بتوازن. أما فمّا بلايص معيّنة، كي الموقف يضغط عليك، ترجع فيها لعادات قديمة.'
  if (balance >= 40)
    return 'شخصيتك فيها برشا قوّة، وفيها زادة عادات تتعبك أكثر ممّا تعاونك. والخبر الباهي: العادات تتبدّل، وأجوبتك تورّي وين بالضبط.'
  return 'نحسّ اللي إنت تعدّي في مرحلة ثقيلة شويّة: برشا من أجوبتك فيها ضغط ولا خوف ولا تعب. هذا موش عيب وموش حكم عليك، هذا وين {@واقف|واقفة} توّا، ومن هوني نبداو.'
}

const short = (s: string, max = 220) =>
  s.length > max ? `${s.slice(0, max).trimEnd()}…` : s

/** The letter, as paragraphs. `seed` keeps the wording stable for one game. */
export function writeLetter(
  report: AiReport,
  gender: string | null | undefined,
  seed: number,
): string[] {
  const g = (s: string) => personalize(s, gender, null)
  const pick = <T,>(list: T[], salt: number) => list[(seed + salt) % list.length]
  const p: string[] = []

  p.push(`${report.name}، ${pick(OPENERS, 0)} ${g(overall(report.balance))}`)

  // Every answer balanced: either very balanced or answered what looks good
  if (!report.workOn.length) {
    p.push(
      g(
        'أما بالصراحة؟ ولا جواب واحد مايل. يا {@إنت متوازن|إنتي متوازنة} بشكل نادر، يا {@جاوبت|جاوبتي} باللي يبان باهي موش باللي يشبهلك. الحاجة الوحيدة اللي ما يقدر حتى اختبار يقيسها هي الصدق مع روحك. عاود العب وجاوب بقلبك، والرسالة الجاية تكون عليك إنت بالحق.',
      ),
    )
    p.push(pick(CLOSERS, 2))
    return p
  }

  const top = [...report.dims].sort((x, y) => y.score - x.score)[0]
  const main = report.workOn[0]
  p.push(
    g(
      top && top.score >= 67 && top.dim !== main.dim
        ? `أقوى حاجة فيك هي ${top.emoji} ${top.label}، وهاذي حاجة تنجم تتّكى عليها. وأكثر حاجة تحتاج تخدم عليها: "${main.leanName}".`
        : `أكثر حاجة لفتت انتباهي فيك: "${main.leanName}". هاذي اللي باش نبداو بيها.`,
    ),
  )

  // Patterns that feed each other: the part the per-topic cards can't say
  const leanOf = new Map(report.dims.map((d) => [d.dim, d.level !== 'strong' ? d.lean : null]))
  const links = LINKS.filter(
    ([d1, p1, d2, p2]) => leanOf.get(d1) === p1 && leanOf.get(d2) === p2,
  ).slice(0, 2)
  if (links.length) {
    p.push(g(`وحاجة مهمّة: المواضيع عندك موش منفصلة. ${links[0][4]}`))
    if (links[1]) p.push(g(`ونفس الحكاية في بلاصة أخرى: ${links[1][4]}`))
  }

  // The most telling answer, quoted back
  const quote = main.evidence[0]
  if (quote && main.lean) {
    p.push(
      g(
        `وقتلي سألتك «${quote.question}»، {@قلتلي|قلتيلي}: «${quote.answer}». ${MIRROR[main.dim][main.lean]}`,
      ),
    )
  }

  // Answers that go both ways
  const mixed = report.workOn.find((w) => w.otherName)
  if (mixed) {
    p.push(
      g(
        `ولاحظت حاجة أخرى: في ${mixed.emoji} ${mixed.label}، أجوبتك ماشية في الزوز اتجاهات، مرّة "${mixed.leanName}" ومرّة "${mixed.otherName}". الناس اللي هكّا عادة يتقلّبو بين الطرفين حسب الموقف: يبلعو حتى يفيض الكاس، ولا يهربو حتى يندمو. الحل موش إنك تختار طرف، الحل تلقى الوسط وتقعد فيه.`,
      ),
    )
  }

  // The open answer, in the player's own words
  if (report.open) {
    const n = Number(report.open.id.slice(8))
    const reply = OPEN_REPLY[n]
    p.push(
      g(
        `وفي الآخر، كي سألتك «${report.open.question}»، {@قلت|قلتي}: «${short(report.open.answer)}». ${reply ?? ''}`.trim(),
      ),
    )
  }

  const step = main.tips[0]
  if (step) p.push(`لو نختارلك حاجة وحدة تبدا بيها من الجمعة هاذي: ${step}`)
  p.push(pick(CLOSERS, 1))
  return p
}
